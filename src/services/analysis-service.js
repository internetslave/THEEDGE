import { AI_TTL } from '../config/constants.js';
import { env } from '../config/env.js';
import { getRepository } from '../lib/repository/index.js';
import { logger } from '../lib/logger.js';

const aiCache = {};
const aiInflight = {};
const analysisLogger = logger.child({ component: 'analysis-service', provider: 'Anthropic' });

function isFresh(cache, key, ttl) {
  return cache[key] && (Date.now() - cache[key].ts < ttl);
}

function cloneAnalysisData(data) {
  return data ? JSON.parse(JSON.stringify(data)) : null;
}

function getConfidenceBand(confidence) {
  if (confidence >= 82) return 'High conviction, still market-sensitive';
  if (confidence >= 68) return 'Measured edge with known uncertainty';
  return 'Lean only — variance remains high';
}

function getUncertaintyNote(analysis) {
  const riskFactor = safeRiskFactor(analysis);
  if (riskFactor) return riskFactor;
  if ((analysis.confidence || 0) >= 82) return 'Even strong model leans can be overturned by late news, lineup changes, or price movement.';
  if ((analysis.confidence || 0) >= 68) return 'Treat this as an informed edge, not a guaranteed result — matchup variance still matters.';
  return 'This reads as a lower-conviction lean and should be weighed carefully against price and late context.';
}

function safeRiskFactor(analysis) {
  const risk = safeArray(analysis?.keyFactors).find((factor) => String(factor?.label || '').toLowerCase().includes('risk'));
  return typeof risk?.value === 'string' && risk.value.trim() ? risk.value.trim() : '';
}

function decorateAnalysis(analysis, { cached = false, event = null } = {}) {
  if (!analysis) return null;
  const decorated = cloneAnalysisData(analysis);
  const generatedAt = decorated._meta?.generatedAt || Date.now();
  const confidence = Number.parseInt(decorated.confidence, 10) || 0;

  decorated.disclaimer = decorated.disclaimer
    || 'AI-generated analysis based on available market context and model interpretation. Treat it as guidance, not certainty.';
  decorated._meta = {
    provider: 'EdgeIQ AI analysis',
    sourceType: 'generated_insight',
    generatedAt,
    cached,
    cacheTtlSec: Math.round(AI_TTL / 1000),
    eventId: event?.id || decorated._meta?.eventId || null,
    inputType: event?.id?.startsWith('manual_') ? 'manual_scenario' : 'market_event',
    competition: event?.comp || null,
    venue: event?.venue || null,
    confidenceBand: getConfidenceBand(confidence),
    uncertaintyNote: getUncertaintyNote(decorated),
    sourceAttribution: 'Generated by EdgeIQ using model inference and the inputs supplied to the analysis request.',
  };

  return decorated;
}

function safeArray(value) {
  return Array.isArray(value) ? value : [];
}

function shouldPersistAnalysis(event) {
  return !!event?.id && !String(event.id).startsWith('manual_');
}

