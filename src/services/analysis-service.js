export function getCachedAnalysis(eventId) {
  return decorateAnalysis(aiCache[eventId]?.data || null, { cached: true });
}

export function hasFreshAnalysis(eventId) {
  return isFresh(aiCache, eventId, AI_TTL);
}

export async function deleteCachedAnalysis(eventId) {
  delete aiCache[eventId];
  await getRepository().removeAiCacheEntry(eventId);
  analysisLogger.info('analysis.cache.deleted', { eventId });
}

export async function restorePersistedAnalysisCache() {
  const restoredEntries = await getRepository().restoreAiCache();
  let restored = 0;

  for (const [id, entry] of Object.entries(restoredEntries)) {
    aiCache[id] = entry;
    restored += 1;
  }

  analysisLogger.info('analysis.cache.restored', { entryCount: restored });

  return restored;
}

export async function analyseMatch(event, playerMarkets = null) {
  if (!env.ANTHROPIC_API_KEY) return null;
  if (shouldPersistAnalysis(event) && isFresh(aiCache, event.id, AI_TTL)) {
    analysisLogger.debug('analysis.cache.hit', { eventId: event.id });
    return decorateAnalysis(aiCache[event.id].data, { cached: true, event });
  }

  if (aiInflight[event.id]) {
    analysisLogger.debug('analysis.inflight.dedup', { eventId: event.id });
    return aiInflight[event.id];
  }

  const promise = doAnalyseMatch(event, playerMarkets).finally(() => {
    delete aiInflight[event.id];
  });
  aiInflight[event.id] = promise;

  return promise;
}

async function doAnalyseMatch(event, playerMarkets = null) {
  try {
    const home = event.home;
    const away = event.away;
    const sport = event.sport;
    const oddsLine = `${home} @ ${event.homeOdds}, ${away} @ ${event.awayOdds}${event.drawOdds ? `, Draw @ ${event.drawOdds}` : ''}`;
    const recOptions = event.drawOdds ? `"${home}", "${away}", or "Draw"` : `"${home}" or "${away}"`;
    const favTeam = event.homeOdds <= event.awayOdds ? home : away;
    const dogTeam = event.homeOdds <= event.awayOdds ? away : home;
    const sportContext = getSportContext(sport);

    let playerSection = '';
    if (playerMarkets) {
      if (sport === 'AFL') {
        if (playerMarkets.firstGoal?.length) playerSection += `\nFIRST GOAL / ANYTIME GOAL SCORER OPTIONS: ${playerMarkets.firstGoal.join(', ')}\n`;
        if (playerMarkets.disposals?.length) playerSection += `DISPOSALS (20+/25+) PLAYER OPTIONS: ${playerMarkets.disposals.join(', ')}\n`;
      } else if (sport === 'NRL') {
        if (playerMarkets.tryscorers?.length) playerSection += `\nTRY SCORER OPTIONS: ${playerMarkets.tryscorers.join(', ')}\n`;
      } else if (sport === 'NBA') {
        if (playerMarkets.pointsPlayers?.length) playerSection += `\nPLAYER POINTS OPTIONS: ${playerMarkets.pointsPlayers.join(', ')}\n`;
      }
    }

    const prompt = `You are a sharp sports betting analyst covering Australian and international markets. Analyse this match and return ONLY a JSON object — no markdown, no explanation outside the JSON.

MATCH: ${home} vs ${away}
SPORT: ${sport}
ODDS: ${oddsLine}
${event.comp ? `COMPETITION: ${event.comp}\n` : ''}${event.venue ? `VENUE: ${event.venue}\n` : ''}${event.context ? `EXTRA USER CONTEXT: ${event.context}\n` : ''}${sportContext ? `\n${sportContext}\n` : ''}${playerSection}
Draw on your sports knowledge to produce SPECIFIC, REALISTIC analysis, but never invent facts. If you are not confident about an exact stat, lineup item, scoreline, or recent result, stay qualitative instead of guessing. Use actual numbers, player names, and historical references only when you can state them confidently.
Use calibrated language. Never imply certainty, guaranteed wins, or sure things. Frame the recommendation as a stronger side, lean, or edge, and acknowledge the key uncertainty where relevant.

Return this exact JSON structure with ALL fields filled in:

{
  "recommendation": <one of ${recOptions}>,
  "confidence": <integer 50-95>,
  "valueBet": <true if the recommended team's odds represent genuine value, false otherwise>,
  "summary": "<2-3 sentence punchy verdict that explains WHY this is the pick, referencing specific form or stats>",
  "form": {
    "home": "<${home} last 5 results e.g. W W L W W — with a specific note about their current momentum, scoring avg, or key players>",
    "away": "<${away} last 5 results e.g. L W W L W — with a specific note about their current momentum, scoring avg, or key players>"
  },
  "headToHead": "<Specific H2H record between these teams, e.g. '${home} have won 7 of the last 10 meetings. They won the most recent clash 22-14 in Round 18 last season.' Include actual recent results if known.>",
  "venueEdge": "<Specific venue/home court advantage or disadvantage, referencing the actual arena/stadium, home record this season, and any travel/scheduling factors for ${away}>",
  "keyFactors": [
    {"icon": "⚡", "label": "Key Reason", "value": "<The single most decisive factor — use sport-specific stats and player names>"},
    {"icon": "📊", "label": "Form Edge", "value": "<Specific form stat with numbers — scoring averages, recent results, efficiency metrics>"},
    {"icon": "🏟️", "label": "Venue / Schedule", "value": "<Home court/ground advantage with specific record, and any back-to-back or travel fatigue>"},
    {"icon": "⚠️", "label": "Risk", "value": "<Main risk to the pick — injury, player availability, hot opponent form, or statistical anomaly>"}
  ],
  "bettingAngle": "<One sharp betting insight referencing the specific odds above — e.g. line value, market inefficiency, or why the favourite/underdog price is correct or incorrect given specific stats.>",
  "props": {
    "ou": <AFL/NRL/NBA/Soccer only: "over" or "under" — your pick on the total points/goals market, null for UFC/Boxing>,
    "ouReason": "<10-15 words max explaining the over/under pick — scoring pace, defensive stats, weather, etc. null for UFC/Boxing>",
    "margin": <AFL only: your pick from exactly one of: "${favTeam} 1–39", "${favTeam} 40+", "${dogTeam} 1–39", "${dogTeam} 40+" — use the en-dash character, null for all other sports>,
    "btts": <Soccer only: "yes" or "no" — both teams to score, null for all other sports>,
    "mov": <UFC/Boxing only: e.g. "${home} by KO/TKO" or "${away} by Decision" or "${away} by Submission" — the most likely finish, null for other sports>,
    "dist": <UFC/Boxing only: "yes" or "no" — does the fight go the full distance, null for other sports>,
    "distReason": "<UFC/Boxing only: 10-15 words why it does/doesn't go the distance, null for other sports>"
  },
  "playerPicks": {
    "firstGoal": <AFL only if FIRST GOAL OPTIONS provided: exact player name from the list most likely to kick the first goal, null otherwise>,
    "anyGoal": <AFL only if FIRST GOAL OPTIONS provided: exact player name from the list most likely to kick 2+ goals (can differ from firstGoal), null otherwise>,
    "dis20": <AFL only if DISPOSALS OPTIONS provided: exact player name from the list most likely to record 20+ disposals, null otherwise>,
    "dis25": <AFL only if DISPOSALS OPTIONS provided: exact player name from the list most likely to record 25+ disposals (can differ from dis20), null otherwise>,
    "firstTry": <NRL only if TRY SCORER OPTIONS provided: exact player name from the list most likely to score the first try, null otherwise>,
    "anyTry": <NRL only if TRY SCORER OPTIONS provided: exact player name most likely to score anytime (can differ from firstTry), null otherwise>,
    "pts20": <NBA only if PLAYER POINTS OPTIONS provided: exact player name from the list most likely to score 20+ points, null otherwise>,
    "pts30": <NBA only if PLAYER POINTS OPTIONS provided: exact player name from the list most likely to score 30+ points (can differ from pts20), null otherwise>
  }
}`;

    const response = await fetch('https://api.anthropic.com/v1/messages', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'x-api-key': env.ANTHROPIC_API_KEY,
        'anthropic-version': '2023-06-01',
      },
      body: JSON.stringify({
        model: 'claude-haiku-4-5-20251001',
        max_tokens: 2000,
        messages: [{ role: 'user', content: prompt }],
      }),
    });

    const data = await response.json();
    if (data.error) {
      const message = data.error?.message || JSON.stringify(data.error);
      analysisLogger.error('analysis.upstream.error', {
        eventId: event.id,
        error: { name: 'AnthropicError', message },
      });
      if (message.includes('credit') || message.includes('billing')) {
        return { _error: 'credits', message: 'AI credits exhausted — top up at console.anthropic.com' };
      }
      return null;
    }

    const stopReason = data.stop_reason;
    if (stopReason === 'max_tokens') {
      analysisLogger.warn('analysis.response.truncated', { eventId: event.id, stopReason });
    }

    const raw = data.content?.[0]?.text || '';
    const jsonMatch = raw.match(/\{[\s\S]*\}/);
    const jsonStr = jsonMatch ? jsonMatch[0] : raw.replace(/```json|```/g, '').trim();

    let analysis;
    try {
      analysis = JSON.parse(jsonStr);
    } catch {
      let patched = jsonStr.replace(/,\s*$/, '');
      if ((patched.match(/"/g) || []).length % 2 !== 0) patched += '"';

      const openArrays = (patched.match(/\[/g) || []).length - (patched.match(/\]/g) || []).length;
      for (let index = 0; index < openArrays; index += 1) patched += ']';

      const openObjects = (patched.match(/\{/g) || []).length - (patched.match(/\}/g) || []).length;
      for (let index = 0; index < openObjects; index += 1) patched += '}';

      analysis = JSON.parse(patched);
      analysisLogger.warn('analysis.response.recovered_json', { eventId: event.id });
    }

    if (!analysis.recommendation || !analysis.confidence) {
      throw new Error('Missing required AI fields');
    }

    const decorated = decorateAnalysis(analysis, { cached: false, event });
    if (shouldPersistAnalysis(event)) {
      const entry = { data: decorated, ts: Date.now() };
      aiCache[event.id] = entry;
      getRepository()
        .saveAiCacheEntry(event.id, entry)
        .catch((error) => analysisLogger.error('analysis.cache.persist_failed', {
          eventId: event.id,
          error: { name: error.name, message: error.message },
        }));
    }
    analysisLogger.info('analysis.generated', {
      eventId: event.id,
      sport,
      confidence: decorated.confidence,
      recommendation: decorated.recommendation,
      recoveredJson: stopReason === 'max_tokens',
      cached: false,
      persisted: shouldPersistAnalysis(event),
    });

    return decorated;
  } catch (error) {
    analysisLogger.error('analysis.failed', {
      eventId: event.id,
      sport: event.sport,
      error: { name: error.name, message: error.message },
    });
    return null;
  }
}

